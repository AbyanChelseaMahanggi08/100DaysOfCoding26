public class Day17{
public static void main(String[] args) {

// Operator Penugasan +=, -=, *=, /=, %=

int a = 50;

// Menambahkan nilai a dengan 20
a += 20;
System.out.println("Hasil a += 50 = " + a);

// Mengurangi nilai a dengan 20
a -= 20;
System.out.println("Hasil a -= 20 = " + a);

// Mengkalikan nilai a dengan 2
a *= 2;
System.out.println("Hasil a *= 2  = " + a);

// Membagi nilai a dengan 10
a /= 10;
System.out.println("Hasil a /= 10 = " + a);

// Mencari sisa bagi nilai a dengan 3
a %= 3;
System.out.println("Hasil a %= 3  = " + a);

}
}
