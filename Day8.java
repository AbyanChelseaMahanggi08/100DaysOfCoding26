// Pengenalan Deklarasi, Inisialisasi Dan Update Variable

public class Day8 {
 public static void main(String[] args) {

 // Deklarasi digunakan untuk membuat sebuah variable dengan tipe data tertentu
 int Nilai;

 // Inisialisasi digunakan untuk memberikan nilai awal
 Nilai = 75;
 System.out.println("Nilai Ujian Awal = " + Nilai);

 // Update digunakan untuk mengupdate nilai awal menjadi nilai yang baru
 Nilai = 90;
 System.out.println("Nilai Ujian Baru = " + Nilai);


 }
}
