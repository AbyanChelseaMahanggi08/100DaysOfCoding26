// Mempelajari Tipe Data Karakter //Program mempe(char) dan Boolean (boolean)

public class Day6 {
 public static void main(String[] args) {

 // char digunakan untuk menyimpan satu karakter.   
 char inisial = 'A';
 char simbol = '#';
 
 // boolean digunakan untuk menyimpan dua nilai yaitu, TRUE/FALSE (BENAR/SALAH)
 boolean sudahMakan = true;
 boolean sudahMinum = false; 

 // Hasil dari kedua tipe data yang kita buat
 System.out.println("Inisial = " + inisial);
 System.out.println("Simbol = " + simbol);

 System.out.println("Sudah Makan = " + sudahMakan);
 System.out.println("Sudah Minum = " + sudahMinum);
 }
}
